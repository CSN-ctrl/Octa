CREATE OR REPLACE FUNCTION purchase_plot(
  p_plot_id INTEGER,
  p_buyer_wallet TEXT,
  p_buyer_email TEXT,
  p_price NUMERIC,
  p_currency TEXT DEFAULT 'xBGL'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_w TEXT := lower(p_buyer_wallet);
  v_e TEXT := lower(trim(p_buyer_email));

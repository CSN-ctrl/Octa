CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- -----------------------------------------------------------------------------
-- Enums
-- -----------------------------------------------------------------------------
DO $$ BEGIN
  CREATE TYPE automation_type AS ENUM ('auto_reinvest', 'recurring_deposit', 'rebalance');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE manager_status AS ENUM ('pending', 'approved', 'rejected');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
DO $$ BEGIN
  CREATE TYPE portfolio_status AS ENUM ('active', 'paused', 'closed');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

-- -----------------------------------------------------------------------------
-- Core game / world
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS star_systems (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  owner_wallet TEXT NOT NULL,
  chain_id INTEGER,
  rpc_url TEXT,
  subnet_id TEXT,
  status TEXT,
  planets TEXT[],
  treasury_balance JSONB,
  tribute_percent NUMERIC,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS planets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  owner_wallet TEXT NOT NULL,
  star_system_id UUID REFERENCES star_systems(id) ON DELETE SET NULL,
  planet_type TEXT,
  node_type TEXT,
  ip_address TEXT,
  status TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS plots (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  coord_x NUMERIC NOT NULL,
  coord_y NUMERIC NOT NULL,
  owner_wallet TEXT,
  planet_id UUID REFERENCES planets(id) ON DELETE SET NULL,
  zone_type TEXT,
  building_stage INTEGER,
  production_rate NUMERIC,
  metadata_cid TEXT,
  workers JSONB,
  last_tick TIMESTAMPTZ,
  booking_status TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- Balances & identities
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_balances (
  wallet_address TEXT PRIMARY KEY,
  xbgl_balance NUMERIC DEFAULT 0,
  chaos_balance NUMERIC DEFAULT 0,
  avax_balance NUMERIC DEFAULT 0,
  sc_balance NUMERIC DEFAULT 0,
  last_synced TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS digital_identities (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  wallet_address TEXT NOT NULL,
  name TEXT NOT NULL,
  identity_type TEXT,
  avatar_cid TEXT,
  metadata_cid TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS user_wallets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  wallet_address TEXT NOT NULL,
  wallet_label TEXT,
  connected_at TIMESTAMPTZ DEFAULT NOW(),
  last_used_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, wallet_address)
);

CREATE INDEX IF NOT EXISTS idx_user_wallets_user_id ON user_wallets(user_id);
CREATE INDEX IF NOT EXISTS idx_user_wallets_wallet_address ON user_wallets(wallet_address);

-- -----------------------------------------------------------------------------
-- Portfolios & automation
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS portfolios (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_wallet TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT,
  status portfolio_status DEFAULT 'active',
  initial_investment NUMERIC,
  current_value NUMERIC,
  roi_percent NUMERIC,
  risk_level TEXT,
  performance_history JSONB,
  auto_reinvest_enabled BOOLEAN DEFAULT false,
  auto_reinvest_percent NUMERIC,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS portfolio_managers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  wallet_address TEXT NOT NULL,
  display_name TEXT NOT NULL,
  bio TEXT,
  approval_status manager_status DEFAULT 'pending',
  applied_at TIMESTAMPTZ,
  approved_at TIMESTAMPTZ,
  management_fee_percent NUMERIC,
  roi_annualized NUMERIC,
  sharpe_ratio NUMERIC,
  total_followers INTEGER DEFAULT 0,
  track_record JSONB,
  verified BOOLEAN DEFAULT false,
  performance_start_date TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS portfolio_followers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  manager_wallet TEXT NOT NULL,
  follower_wallet TEXT NOT NULL,
  active BOOLEAN DEFAULT true,
  allocation_amount NUMERIC,
  copy_percent NUMERIC,
  started_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS automation_settings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  owner_wallet TEXT NOT NULL,
  portfolio_id UUID REFERENCES portfolios(id) ON DELETE SET NULL,
  automation_type automation_type NOT NULL,
  enabled BOOLEAN DEFAULT true,
  config JSONB,
  last_executed TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS recurring_payments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  from_wallet TEXT NOT NULL,
  to_wallet TEXT,
  amount NUMERIC NOT NULL,
  token_type TEXT,
  frequency TEXT NOT NULL,
  next_payment_date TIMESTAMPTZ NOT NULL,
  last_payment_date TIMESTAMPTZ,
  payment_count INTEGER DEFAULT 0,
  enabled BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- -----------------------------------------------------------------------------
-- Marketplace & ledger
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS marketplace_listings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  seller_wallet TEXT NOT NULL,
  asset_type TEXT NOT NULL,
  asset_id TEXT NOT NULL,
  price NUMERIC NOT NULL,
  token_type TEXT,
  description TEXT,
  metadata JSONB,
  status TEXT DEFAULT 'active',
  buyer_wallet TEXT,
  listed_at TIMESTAMPTZ DEFAULT NOW(),
  sold_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS transactions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  tx_hash TEXT NOT NULL UNIQUE,
  from_address TEXT NOT NULL,
  to_address TEXT,
  amount NUMERIC,
  token_type TEXT,
  transaction_type TEXT,
  type TEXT NOT NULL,
  status TEXT DEFAULT 'completed',
  plot_id INTEGER REFERENCES plots(id) ON DELETE SET NULL,
  block_number INTEGER,
  metadata JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_transactions_plot_id ON transactions(plot_id);
CREATE INDEX IF NOT EXISTS idx_transactions_from ON transactions(from_address);
CREATE INDEX IF NOT EXISTS idx_transactions_to ON transactions(to_address);

-- -----------------------------------------------------------------------------
-- Factions / NPCs / economy / invites
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS factions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  founder_wallet TEXT NOT NULL,
  governance_model TEXT,
  member_wallets TEXT[],
  plot_ids INTEGER[],
  treasury_balance JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS npcs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  assigned_plot_id INTEGER REFERENCES plots(id) ON DELETE SET NULL,
  employer_wallet TEXT,
  nft_id INTEGER,
  loyalty_score NUMERIC,
  personality_vector JSONB,
  skills JSONB,
  employment_history JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS economy_ticks (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  plot_id INTEGER REFERENCES plots(id) ON DELETE SET NULL,
  tick_number INTEGER NOT NULL,
  chaos_tokens_generated INTEGER,
  resources_generated JSONB,
  processed_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS black_market_invites (
  wallet_address TEXT PRIMARY KEY,
  invite_code TEXT NOT NULL,
  invited_by TEXT,
  invited_at TIMESTAMPTZ DEFAULT NOW(),
  used BOOLEAN DEFAULT false
);

-- -----------------------------------------------------------------------------
-- Registry & documents
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ownership_registry (
  wallet_address TEXT PRIMARY KEY,
  email TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS plot_purchases (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  plot_id INTEGER NOT NULL REFERENCES plots(id) ON DELETE CASCADE,
  buyer_wallet TEXT NOT NULL,
  purchase_price NUMERIC NOT NULL,
  currency TEXT DEFAULT 'xBGL',
  status TEXT DEFAULT 'pending',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_plot_purchases_status ON plot_purchases(status);

CREATE TABLE IF NOT EXISTS cities (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  planet_id UUID NOT NULL REFERENCES planets(id) ON DELETE CASCADE,
  metadata JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_cities_planet_id ON cities(planet_id);

CREATE TABLE IF NOT EXISTS plot_documents (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  plot_id INTEGER NOT NULL REFERENCES plots(id) ON DELETE CASCADE,
  owner_wallet TEXT,
  document_type TEXT NOT NULL,
  document_url TEXT NOT NULL,
  filename TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_plot_documents_plot_id ON plot_documents(plot_id);

-- -----------------------------------------------------------------------------
-- Deposits & FX
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exchange_rates (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  from_token TEXT NOT NULL,
  to_token TEXT NOT NULL,
  rate NUMERIC NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (from_token, to_token)
);

CREATE TABLE IF NOT EXISTS hot_wallets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  network_id TEXT NOT NULL UNIQUE,
  address TEXT NOT NULL,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS usdc_deposits (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_email TEXT NOT NULL,
  user_wallet TEXT,
  network_id TEXT NOT NULL,
  usdc_amount NUMERIC NOT NULL,
  xbgl_amount NUMERIC NOT NULL,
  tx_hash TEXT,
  hot_wallet_address TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'failed')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  confirmed_at TIMESTAMPTZ,
  metadata JSONB
);

CREATE INDEX IF NOT EXISTS idx_usdc_deposits_user_email ON usdc_deposits(user_email);
CREATE INDEX IF NOT EXISTS idx_usdc_deposits_status ON usdc_deposits(status);

-- -----------------------------------------------------------------------------
-- Affiliates
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS affiliates (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  wallet_address TEXT UNIQUE NOT NULL,
  affiliate_code TEXT UNIQUE NOT NULL,
  commission_rate NUMERIC(5,4) DEFAULT 0.15,
  total_referrals INTEGER DEFAULT 0,
  total_commission NUMERIC(20,8) DEFAULT 0,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  application_reason TEXT,
  application_date TIMESTAMPTZ DEFAULT NOW(),
  reviewed_by TEXT,
  reviewed_at TIMESTAMPTZ,
  rejection_reason TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS user_affiliate_codes (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  wallet_address TEXT NOT NULL UNIQUE,
  affiliate_code TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS affiliate_referrals (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  affiliate_code TEXT NOT NULL,
  referrer_wallet TEXT NOT NULL REFERENCES affiliates(wallet_address) ON DELETE CASCADE,
  referred_wallet TEXT NOT NULL,
  referred_email TEXT,
  commission_rate NUMERIC(20,8) NOT NULL,
  commission_amount NUMERIC(20,8) NOT NULL,
  purchase_amount NUMERIC(20,8) NOT NULL,
  plot_ids INTEGER[] NOT NULL,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'cancelled')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  paid_at TIMESTAMPTZ,
  UNIQUE (referred_wallet)
);

CREATE INDEX IF NOT EXISTS idx_affiliates_code ON affiliates(affiliate_code);
CREATE INDEX IF NOT EXISTS idx_affiliates_status ON affiliates(status);
CREATE INDEX IF NOT EXISTS idx_referrals_referrer ON affiliate_referrals(referrer_wallet);
CREATE INDEX IF NOT EXISTS idx_referrals_status ON affiliate_referrals(status);

-- -----------------------------------------------------------------------------
-- Expert applications & user stats
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS expert_applications (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  full_name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  budget_range TEXT NOT NULL,
  investment_goals TEXT,
  preferred_contact TEXT DEFAULT 'email',
  message TEXT,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'contacted', 'approved', 'rejected')),
  assigned_consultant TEXT,
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  contacted_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS user_stats (
  id UUID PRIMARY KEY,
  total_users INTEGER DEFAULT 0,
  last_updated TIMESTAMPTZ DEFAULT NOW()
);

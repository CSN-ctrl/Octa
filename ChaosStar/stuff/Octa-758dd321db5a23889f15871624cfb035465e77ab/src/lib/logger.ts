/**
 * Centralized logging utility
 * Only logs in development mode to reduce production noise
 */

const isDev = import.meta.env.DEV;

export const logger = {
  log: (...args: any[]) => {
    if (isDev) {
      console.log(...args);
    }
  },
  
  error: (...args: any[]) => {
    // Always log errors, even in production
    console.error(...args);
  },
  
  warn: (...args: any[]) => {
    if (isDev) {
      console.warn(...args);
    }
  },
  
  debug: (...args: any[]) => {
    if (isDev) {
      console.debug(...args);
    }
  },
  
  info: (...args: any[]) => {
    if (isDev) {
      console.info(...args);
    }
  },
  
  // Group related logs
  group: (label: string, fn: () => void) => {
    if (isDev) {
      console.group(label);
      fn();
      console.groupEnd();
    }
  },
  
  // Time operations
  time: (label: string) => {
    if (isDev) {
      console.time(label);
    }
  },
  
  timeEnd: (label: string) => {
    if (isDev) {
      console.timeEnd(label);
    }
  },
};
